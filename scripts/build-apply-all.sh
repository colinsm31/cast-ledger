#!/usr/bin/env bash
# Concatenate all migrations (in order) into supabase/apply_all.sql — a single
# file you can paste into a fresh project's SQL editor to stand up the whole
# schema at once. Re-run this whenever migrations change.
#
# Some early migrations drop tables or empty the sales history (code review
# #22), so the file starts with a check that stops it on any database that
# already has a sales table, and runs as one transaction: if anything stops
# it, nothing after the stop takes effect.
#
# Usage:  ./scripts/build-apply-all.sh
set -euo pipefail

cd "$(dirname "$0")/.."
OUT="supabase/apply_all.sql"

{
  echo "-- ============================================================"
  echo "-- apply_all.sql — GENERATED by scripts/build-apply-all.sh"
  echo "-- All migrations concatenated in order. Do not edit by hand."
  echo "-- Run against a FRESH database (e.g. a new test project) ONLY:"
  echo "-- early migrations drop tables and empty the sales history, so"
  echo "-- the check below refuses any database that already has data."
  echo "-- For sample data afterward, run supabase/seed/tennis_seed.sql."
  echo "-- ============================================================"
  echo
  echo "begin;"
  echo
  echo "do \$\$"
  echo "begin"
  echo "  if to_regclass('public.sales') is not null then"
  echo "    raise exception 'apply_all.sql is only for a brand-new database. This one already has a sales table, so nothing was applied. Apply new migrations one at a time instead.';"
  echo "  end if;"
  echo "end"
  echo "\$\$;"
  echo
  for f in supabase/migrations/*.sql; do
    echo "-- >>> $f"
    cat "$f"
    echo
  done
  echo "commit;"
} > "$OUT"

echo "Wrote $OUT ($(grep -c '^-- >>>' "$OUT") migrations)."
